@pytest.mark.asyncio
async def test_discord_alert_sends_when_webhook_configured(monkeypatch: pytest.MonkeyPatch) -> None:
    """A configured webhook URL must be POSTed with the JSON payload."""
    record = _resolved_record()
    calls = []
    monkeypatch.setattr(discord_alerts, "get_settings", lambda: _settings_with(discord_url="https://discord.example/webhook"))

    class _FakeResponse:
        raise_for_status = lambda self: None

    class _FakeClient:
        def __init__(self, **kwargs) -> None:
            pass

        async def post(self, url: str, json: dict | None = None) -> _FakeResponse:
            calls.append((url, json))
            return _FakeResponse()

        async def __aenter__(self):
            return self

        async def __aexit__(self, exc_type, exc, tb) -> None:
            return None

    fake_httpx = SimpleNamespace(AsyncClient=_FakeClient)
    monkeypatch.setattr(discord_alerts, "httpx", fake_httpx)

    await discord_alerts.send_resolution_alert(record)

    assert len(calls) == 1
    assert calls[0][0] == "https://discord.example/webhook"
    assert calls[0][1]["embeds"][0]["title"] == "🚨 CRITICAL INCIDENT RESOLVED"


