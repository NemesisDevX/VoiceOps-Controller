def test_discord_build_payload_contains_required_fields() -> None:
    """The Discord embed must contain the resolved incident fields and sub-second MTTR."""
    record = _resolved_record()
    record.mttr_seconds = 0.42
    payload = discord_alerts._build_payload(record)

    assert payload["embeds"][0]["title"] == "🚨 CRITICAL INCIDENT RESOLVED"
    assert any(field["name"] == "Executed Command" for field in payload["embeds"][0]["fields"])
    assert any(field["name"] == "Mitigated Target" for field in payload["embeds"][0]["fields"])
    assert any("0.420s (sub-second)" in field["value"] for field in payload["embeds"][0]["fields"])


