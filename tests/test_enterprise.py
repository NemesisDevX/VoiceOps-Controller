def _resolved_record():
    """Open and resolve an incident record, returning it for use in tests."""
    command = ParsedCommand(
        raw_text="kill payment-gateway-pod",
        intent=IntentType.PROCESS_KILL,
        target_process_name="payment-gateway-pod",
        language="en",
    )
    record = incident_log.open_incident("enterprise-token", command, "K8S_CLUSTER")
    result = ExecutionResult(
        success=True,
        intent=IntentType.PROCESS_KILL,
        message="Restarted pod 'payment-gateway-pod'. Anomaly cleared; metrics have recovered.",
        dry_run=False,
        affected_process_name="payment-gateway-pod",
    )
    return incident_log.resolve_incident("enterprise-token", result)


def _settings_with(groq_key: str | None = None, discord_url: str | None = None) -> SimpleNamespace:
    """Return a settings-like object with the requested integration keys."""
    return SimpleNamespace(
        GROQ_API_KEY=SecretStr(groq_key) if groq_key is not None else None,
        GROQ_MODEL="llama3-8b-8192",
        DISCORD_WEBHOOK_URL=discord_url,
        DISCORD_ALERTS_ENABLED=True,
    )


def _fake_groq_factory(content: str):
    """Return a fake AsyncGroq callable that yields a chat completion with the supplied content."""
    def _fake(api_key: str):
        async def _create(**kwargs):
            return SimpleNamespace(
                choices=[SimpleNamespace(message=SimpleNamespace(content=content))]
            )

        return SimpleNamespace(chat=SimpleNamespace(completions=SimpleNamespace(create=_create)))

    return _fake


@pytest.mark.asyncio
async def test_groq_client_returns_none_when_key_missing() -> None:
    """Without a Groq API key the agentic generator should short-circuit and return None."""
    record = _resolved_record()
    monkeypatch = pytest.MonkeyPatch()
    monkeypatch.setattr(groq_client, "get_settings", lambda: _settings_with(groq_key=None))
    try:
        report = await groq_client.generate_groq_post_mortem(record)
        assert report is None
    finally:
        monkeypatch.undo()


@pytest.mark.asyncio
async def test_groq_client_generates_markdown_when_key_present(monkeypatch: pytest.MonkeyPatch) -> None:
    """When a Groq key is present the agentic report should be returned."""
    record = _resolved_record()
    monkeypatch.setattr(groq_client, "get_settings", lambda: _settings_with(groq_key="test-key"))
    monkeypatch.setattr(groq_client, "AsyncGroq", _fake_groq_factory("# AI-Generated Post-Mortem\n\nRCA generated by Groq."))

    report = await groq_client.generate_groq_post_mortem(record)

    assert report is not None
    assert "AI-Generated Post-Mortem" in report


@pytest.mark.asyncio
async def test_groq_client_falls_back_on_api_error(monkeypatch: pytest.MonkeyPatch, caplog: pytest.LogCaptureFixture) -> None:
    """Any Groq exception must be logged and return None so the endpoint can fall back."""
    record = _resolved_record()
    monkeypatch.setattr(groq_client, "get_settings", lambda: _settings_with(groq_key="test-key"))
    monkeypatch.setattr(groq_client, "AsyncGroq", lambda api_key: (_ for _ in ()).throw(RuntimeError("groq failure")))

    with caplog.at_level(logging.WARNING, logger="app.services.groq_client"):
        report = await groq_client.generate_groq_post_mortem(record)

    assert report is None
    assert "Groq post-mortem generation failed" in caplog.text


