    incident_log.resolve_incident(
        "fallback-token",
        ExecutionResult(success=True, intent=IntentType.PROCESS_KILL, message="Recovered.", dry_run=False, affected_process_name="payment-gateway-pod"),
    )
    monkeypatch.setattr(groq_client, "get_settings", lambda: _settings_with(groq_key=None))

    response = client.get("/api/v1/incident/post-mortem", params={"token": "fallback-token"})

    assert response.status_code == 200
    body = response.json()
    assert body["ai_generated"] is False
    assert "# Incident Post-Mortem" in body["markdown"]
