def test_confirm_endpoint_triggers_discord_alert_on_success(client: TestClient, monkeypatch: pytest.MonkeyPatch) -> None:
    """A successful, real confirmation should schedule a Discord resolution alert."""
    from app.core.security import confirmation_registry
    from app.services import system_engine

    command = ParsedCommand(
        raw_text="kill payment-gateway-pod",
        intent=IntentType.PROCESS_KILL,
        target_process_name="payment-gateway-pod",
        language="en",
        requires_confirmation=True,
    )
    pending = confirmation_registry.register(command, mode="K8S_CLUSTER")
    incident_log.open_incident(pending.token, command, "K8S_CLUSTER")

    alerts = []

    async def _capture_alert(r):
        alerts.append(r)

    monkeypatch.setattr(discord_alerts, "send_resolution_alert", _capture_alert)

    async def _fake_cluster_execute(intent, target_name, dry_run=False):
        return ExecutionResult(
            success=True,
            intent=intent,
            message=f"Restarted pod '{target_name}'.",
            dry_run=dry_run,
            affected_process_name=target_name,
        )

    monkeypatch.setattr(system_engine, "cluster_execute", _fake_cluster_execute)

    response = client.post("/api/v1/commands/confirm", json={"token": pending.token, "dry_run": False})

    assert response.status_code == 200
    assert len(alerts) == 1
    assert alerts[0].token == pending.token


